def out_path(review: pathlib.Path) -> pathlib.Path:
    return review / f"{review.name}-dashboard.html"


def write(review: pathlib.Path, con=None) -> tuple[pathlib.Path, bool]:
    """Render the dashboard from the review's database. Returns (path, changed).
    Byte-stable: an unchanged page is not rewritten."""
    own = con is None
    if own:
        con = db.connect(db.db_path(review))
    try:
        page = render(gather(con, review), review)
    finally:
        if own:
            con.close()
    path = out_path(review)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != page:
        path.write_text(page, encoding="utf-8")
        return path, True
    return path, False


def main() -> int:
    ap = argparse.ArgumentParser(description="render reviews/<id>/<id>-dashboard.html from the review's database")
    ap.add_argument("review")
    ap.add_argument("--open", action="store_true", help="open the page in the default browser")
    ap.add_argument("--no-sync", action="store_true", help="render from the database as it is")
    a = ap.parse_args()
    review = rv.resolve(a.review)
    if not a.no_sync:
        db.sync(review, quiet=True)
    path, changed = write(review)
    print(f"{path.relative_to(rv.ROOT)} {'(updated)' if changed else '(unchanged)'}")
    if a.open:
        webbrowser.open(path.as_uri())
    return 0


if __name__ == "__main__":
    sys.exit(main())
