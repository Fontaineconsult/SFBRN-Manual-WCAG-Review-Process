        L.append(f"<h3>{e(pno)} {e(pname)} <span class='muted'>— {dec}/{len(cs)} decided, {fail} failing</span></h3>")
        L.append("<div class='scroll'><table><tr><th>criterion</th><th>outcome</th><th>findings</th><th>evidence</th><th>vendor claim</th></tr>")
