r"""dashboard.py — the review dashboard, rendered from the database.

    python scripts/dashboard.py <review> [--open]

Writes reviews/<id>/<id>-dashboard.html — one self-contained page (no
network, no scripts) built entirely from reviews/<id>/<id>.sqlite. It
answers the reviewer's three questions, in this order (redesigned
2026-09-15 at the reviewer's request — the first version "was very
cluttered and didn't tell me what I need to know"):

1. **508 FPC — did we test every view for each modality?** One row per
   functional performance criterion (no-vision, low-vision, …): views
   done / views sampled, check rows answered / blank / failing, and the
   names of the views still owed.
2. **Views — what are we tracking, and is each one complete?** One row per
   sampled view: the page in words, its locator, the sweep and its triage,
   one cell per modality with the latest run's Result, and "done n/8"
   (seven modality cells with a Result + a triaged sweep).
3. **WCAG 2.2 AA — what passes and what fails?** Headline counts
   (passing / failing / n-a / undecided) and, per principle, a table of
   criteria with the 05 outcome, the findings behind it, the check
   evidence, and the vendor's claim.

Then **Next** (pending walkthrough steps, 05 decisions waiting on a
measured fail, tasks without a verdict) and, folded away, the definition
of done, findings, vendor delta, integrity and the state-log history.
Every run, walkthrough and stage file is a relative link, so the page is
the reviewer's map of the review folder.

Regenerated by every `review_db.py sync` (which validate / status /
coverage / log-test / the probe all call), so it is never behind the
files by more than one command. Deterministic — no timestamps; the header
carries the source hash — so a diff on the committed page means the review
changed. Never hand-edit it.

Colour conventions follow the dataviz status palette: every status carries
a glyph and a word as well as a colour, so nothing reads by colour alone.
"""
