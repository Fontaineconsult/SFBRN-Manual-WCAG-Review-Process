OUTCOME_CLASS = {"Supports": "good", "Partially Supports": "serious", "Does Not Support": "critical",
                 "Not Applicable": "neutral", "Not Evaluated": "empty"}
OUTCOME_GLYPH = {"Supports": "✓", "Partially Supports": "!", "Does Not Support": "✗",
                 "Not Applicable": "–", "Not Evaluated": "·"}
RESULT_CLASS = {"Works": "good", "Works with issues": "warning", "Broken": "critical", "N/A": "neutral",
                "Not set": "pending"}
RESULT_GLYPH = {"Works": "✓", "Works with issues": "!", "Broken": "✗", "N/A": "n", "Not set": "?"}
RESULTED = ("Works", "Works with issues", "Broken", "N/A")
MOD_ABBR = {"no-vision": "NV", "low-vision": "LV", "no-color": "NC", "no-hearing": "NH",
            "no-speech": "NS", "motor": "MO", "cognition": "CO"}
MOD_WORD = {"no-vision": "no vision (screen reader)", "low-vision": "low vision (zoom, contrast)",
            "no-color": "no colour (grayscale)", "no-hearing": "no hearing", "no-speech": "no speech",
            "motor": "motor (keyboard only)", "cognition": "cognition"}
SEV_CLASS = {"Blocker": "critical", "Major": "serious", "Minor": "warning"}
VERDICT_CLASS = {"Pass": "good", "Pass with barriers": "warning", "Fail": "critical"}
VERDICT_GLYPH = {"Pass": "✓", "Pass with barriers": "!", "Fail": "✗"}
SWEEP_CHECKS = ("W1", "W2", "W3")


def e(s) -> str:
    return html.escape("" if s is None else str(s), quote=True)


def plain_locator(loc: str) -> str:
    """The locator without its markdown backticks."""
    return (loc or "").strip().strip("`").strip()


# --------------------------------------------------------------------------
# data — state_data() plus the per-view / per-criterion detail the page needs
# --------------------------------------------------------------------------
def gather(con, review: pathlib.Path) -> dict:
    rid = review.name
    d = db.state_data(con, rid)
    q = lambda sql, **kw: con.execute(sql, {"r": rid, **kw}).fetchall()  # noqa: E731

    # ---- views: one record per sampled view with every cell's latest run ----
    views = []
    d["removed_views"] = [{"view": v, "name": re.sub(r"\s+—\s+proposed \d{4}-\d{2}-\d{2}.*$", "", n or ""), "removed": r}
                          for v, n, r in q("SELECT view_id, name, removed FROM views WHERE review_id=:r AND removed<>'' ORDER BY CASE WHEN view_id LIKE 'S%' THEN 0 ELSE 1 END, CAST(substr(view_id,2) AS INTEGER)")]
    for vid, name, loc, represents, kind in q("""
            SELECT view_id, name, locator, represents, kind FROM views WHERE review_id=:r AND removed=''
            ORDER BY CASE WHEN view_id LIKE 'S%' THEN 0 ELSE 1 END, CAST(substr(view_id,2) AS INTEGER)"""):
        v = {"view": vid, "name": re.sub(r"\s+—\s+proposed \d{4}-\d{2}-\d{2}.*$", "", name or ""),
             "locator": plain_locator(loc), "represents": represents or "", "kind": kind or "", "cells": {}}
        for mod in rv.REQUIRED_MODALITIES:
            row = q("""SELECT run_id, result, tool,
                       (SELECT COUNT(*) FROM check_outcomes ck WHERE ck.review_id=runs.review_id AND ck.run_id=runs.run_id AND ck.outcome=''),
                       (SELECT COUNT(*) FROM check_outcomes ck WHERE ck.review_id=runs.review_id AND ck.run_id=runs.run_id AND ck.outcome IN ('fail','partial'))
                       FROM runs WHERE review_id=:r AND UPPER(view_id)=UPPER(:v) AND modality=:m ORDER BY run_id DESC LIMIT 1""",
                    v=vid, m=mod)
            v["cells"][mod] = ({"run": row[0][0], "result": row[0][1] or "Not set", "tool": row[0][2] or "",
                                "blank": row[0][3], "fails": row[0][4]} if row else None)
        sweeps = q("""SELECT run_id, tool,
                      (SELECT COUNT(*) FROM check_outcomes ck WHERE ck.review_id=runs.review_id AND ck.run_id=runs.run_id
                       AND ck.check_id IN ('W1','W2','W3') AND ck.outcome<>'')
                      FROM runs WHERE review_id=:r AND UPPER(view_id)=UPPER(:v) AND LOWER(tool) IN ('axe','wave') ORDER BY run_id""", v=vid)
        v["sweeps"] = [{"run": s[0], "tool": s[1], "triaged": s[2]} for s in sweeps]
        v["sweep_triaged"] = any(s["triaged"] >= len(SWEEP_CHECKS) for s in v["sweeps"])
        v["cells_done"] = sum(1 for c in v["cells"].values() if c and c["result"] in RESULTED)
        v["done"] = v["cells_done"] + (1 if v["sweep_triaged"] else 0)
        v["done_of"] = len(rv.REQUIRED_MODALITIES) + 1
        v["findings"] = [f for (f,) in q("SELECT finding_id FROM findings WHERE review_id=:r AND withdrawn=0 AND UPPER(view_id)=UPPER(:v) ORDER BY finding_id", v=vid)]
        views.append(v)
    d["views"] = views

    # ---- FPC: per modality, which views are done and which are owed ----
    for f in d["fpc"]:
        mod = f["modality"]
        f["names"] = [f"{code} {name}" for code, name in rv.FPC[mod]]
        f["owed"] = [{"view": v["view"], "name": v["name"],
                      "state": (v["cells"][mod]["result"] if v["cells"][mod] else "not run"),
                      "run": (v["cells"][mod]["run"] if v["cells"][mod] else ""),
                      "blank": (v["cells"][mod]["blank"] if v["cells"][mod] else 0)}
                     for v in views if not (v["cells"][mod] and v["cells"][mod]["result"] in RESULTED)]
        f["done_views"] = [v["view"] for v in views if v["cells"][mod] and v["cells"][mod]["result"] in RESULTED]
        f["broken_views"] = [v["view"] for v in views if v["cells"][mod] and v["cells"][mod]["result"] in ("Broken", "Works with issues")]

    # ---- criteria: outcome, evidence, findings, vendor claim ----
    evidence = {sc: (a, fl) for sc, a, fl in q("""
        SELECT cc.sc, SUM(ck.outcome IN ('pass','fail','partial','n/a')), SUM(ck.outcome IN ('fail','partial'))
        FROM check_outcomes ck JOIN check_criteria cc USING (check_id) WHERE ck.review_id=:r GROUP BY cc.sc""")}
    pending = {sc for (sc,) in q("""
        SELECT DISTINCT cc.sc FROM check_outcomes ck JOIN check_criteria cc USING (check_id)
        JOIN criterion_outcomes co ON co.review_id=ck.review_id AND co.sc=cc.sc
        WHERE ck.review_id=:r AND ck.outcome IN ('fail','partial') AND co.outcome='Not Evaluated'""")}
    findings_by_sc = {}
    for sc, fid in q("""SELECT fc.sc, fc.finding_id FROM finding_criteria fc JOIN findings f USING (review_id, finding_id)
                        WHERE fc.review_id=:r AND f.withdrawn=0 ORDER BY fc.sc, fc.finding_id"""):
        findings_by_sc.setdefault(sc, []).append(fid)
    d["criteria"] = []
    for sc, n, lv, p, pn, o, c, tf, u, rem in q("""
            SELECT w.sc, w.name, w.level, w.principle_no, w.principle, o.outcome, o.vendor_claim, o.task_findings,
                   w.understanding_url, o.remarks FROM wcag_criteria w
            LEFT JOIN criterion_outcomes o ON o.sc=w.sc AND o.review_id=:r
            WHERE w.in_target=1 ORDER BY w.sort_key"""):
        answered, failing = evidence.get(sc, (0, 0))
        claim = next((k for k in ("Partially Supports", "Does Not Support", "Not Applicable", "Not Evaluated", "Supports")
                      if (c or "").startswith(k)), "")
        outcome = o or "Not Evaluated"
        delta = ""
        if claim and outcome != "Not Evaluated" and claim != "Not Evaluated":
            diff = db.CLAIM_RANK.get(outcome, 0) - db.CLAIM_RANK.get(claim, 0)
            delta = "worse" if diff < 0 else "better" if diff > 0 else "same"
        d["criteria"].append({
            "sc": sc, "name": n, "level": lv, "principle_no": str(p), "principle": pn, "outcome": outcome,
            "provisional": "provisional" in (rem or "").lower()[:60],
            "claim": claim, "claim_full": c or "", "delta": delta, "url": u or "",
            "findings": findings_by_sc.get(sc, []), "rollup": tf or "",
            "answered": answered or 0, "failing": failing or 0, "pending": sc in pending})
    crit = d["criteria"]
    d["wcag_summary"] = {
        "passing": sum(1 for c in crit if c["outcome"] == "Supports"),
        "failing": sum(1 for c in crit if c["outcome"] in ("Partially Supports", "Does Not Support")),
        "na": sum(1 for c in crit if c["outcome"] == "Not Applicable"),
        "undecided": sum(1 for c in crit if c["outcome"] == "Not Evaluated"),
        "undecided_pending": sum(1 for c in crit if c["outcome"] == "Not Evaluated" and c["pending"]),
        "undecided_evidenced": sum(1 for c in crit if c["outcome"] == "Not Evaluated" and c["answered"] and not c["pending"]),
        "undecided_blank": sum(1 for c in crit if c["outcome"] == "Not Evaluated" and not c["answered"]),
    }

    # ---- the rest (folded) ----
    d["findings_list"] = [{"id": f, "severity": s or "", "section": sec, "view": v or "", "task": t or "",
                           "where": w or "", "withdrawn": bool(wd), "criteria": [x for x in (c or "").split(",") if x],
                           "runs": sorted(set((r or "").split(",")) - {""})}
                          for f, s, sec, v, t, w, wd, c, r in q("""
        SELECT f.finding_id, f.severity, f.section, f.view_id, f.task_id, f.where_text, f.withdrawn,
               (SELECT group_concat(sc) FROM (SELECT sc FROM finding_criteria fc WHERE fc.review_id=f.review_id AND fc.finding_id=f.finding_id ORDER BY sc)),
               (SELECT group_concat(run_id) FROM (SELECT run_id FROM finding_runs fr WHERE fr.review_id=f.review_id AND fr.finding_id=f.finding_id ORDER BY run_id))
        FROM findings f WHERE f.review_id=:r
        ORDER BY f.withdrawn, CASE WHEN f.severity LIKE 'Blocker%' THEN 0 WHEN f.severity LIKE 'Major%' THEN 1 WHEN f.severity LIKE 'Minor%' THEN 2 ELSE 3 END, f.finding_id""")]
    d["measured_detail"] = [{"sc": sc, "name": n, "check": c, "runs": (runs or "").split(",")}
                            for sc, n, c, runs in q("""
        SELECT cc.sc, w.name, ck.check_id, group_concat(ck.run_id)
        FROM check_outcomes ck JOIN check_criteria cc USING (check_id)
        JOIN criterion_outcomes co ON co.review_id=ck.review_id AND co.sc=cc.sc
        JOIN wcag_criteria w ON w.sc=cc.sc
        WHERE ck.review_id=:r AND ck.outcome IN ('fail','partial') AND co.outcome='Not Evaluated'
        GROUP BY cc.sc, ck.check_id ORDER BY cc.sc, ck.check_id""")]
    d["tasks_detail"] = [{"task": t, "name": n, "verdict": v}
                         for t, n, v in q("SELECT task_id, name, verdict FROM tasks WHERE review_id=:r ORDER BY task_id")]
    d["integrity_detail"] = db.integrity(con, rid)
    d["unanswered_runs"] = [{"run": r, "view": v, "modality": m, "tool": t, "blank": n} for r, v, m, t, n in q("""
        SELECT r.run_id, r.view_id, r.modality, r.tool, COUNT(*) FROM runs r JOIN check_outcomes ck USING (review_id, run_id)
        JOIN views v ON v.review_id=r.review_id AND UPPER(v.view_id)=UPPER(r.view_id)
        WHERE r.review_id=:r AND ck.outcome='' AND v.removed='' GROUP BY r.run_id ORDER BY COUNT(*) DESC, r.run_id""")]
    log = review / "state-log.md"
    d["history"] = []
    if log.exists():
        for ln in log.read_text(encoding="utf-8").splitlines():
            if ln.startswith("| 20"):
                d["history"].append([c.strip() for c in ln.strip().strip("|").split("|")])
    return d


